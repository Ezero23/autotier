export type AutotierLocale = keyof typeof autotierTranslations;

function flattenAutotierStrings(
  value: unknown,
  path: string[] = [],
  result: string[] = [],
): string[] {
  if (typeof value === "string") {
    result.push(path.join("."));
  } else if (typeof value === "object" && value !== null) {
    for (const [key, child] of Object.entries(value)) {
      flattenAutotierStrings(child, [...path, key], result);
    }
  }
  return result;
}

